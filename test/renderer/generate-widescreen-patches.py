"""Pack the pinned, previously researched TWiLight Menu++ widescreen collection.

Inputs are an inventory.json and its patches/ directory; no downloads or ROMs.
Checks the original Git blob and SHA-256 before generating the bundled resource.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct


def generate(inventory, directory):
    entries = json.loads(inventory.read_text(encoding='utf-8'))
    words, profiles = [], []
    for entry in entries['patches']:
        data = (directory / entry['file']).read_bytes()
        assert hashlib.sha256(data).hexdigest() == entry['sha256'], entry['file']
        assert hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest() == entry['git_blob']
        assert len(data) == entry['bytes'] and len(data) % 8 == 0
        if not data:
            continue
        values = list(struct.unpack('<' + 'I' * (len(data) // 4), data))
        simple = entry['classification'] == 'simple_q12_aspect_only'
        if simple:
            assert len(values) % 6 == 0
            for i in range(0, len(values), 6):
                guard, old, write, new, reset, zero = values[i:i+6]
                assert guard >> 28 == 9 and write >> 28 == 1
                assert guard & 0xfffffff == write & 0xfffffff
                assert (old, new, reset, zero) == (0x1555, 0x199a, 0xd2000000, 0)
        profiles.append(f'    {{"{Path(entry["file"]).stem}", 0x{entry["filename_crc"]}, {len(words)}, {len(values)}, {str(simple).lower()}}},')
        words.extend(values)
    text = ['// Generated by test/renderer/generate-widescreen-patches.py. Do not edit.',
            '// Community-authored experimental widescreen codes; see WideGamePatches.h for provenance.',
            '// Pinned upstream revision: ' + entries['upstream_revision'],
            '#pragma once', '', 'namespace melonDS::WideGamePatches', '{',
            'inline constexpr u32 CommunityWords[] = {']
    for i in range(0, len(words), 8):
        text.append('    ' + ', '.join(f'0x{x:08X}' for x in words[i:i+8]) + ',')
    text.extend(['};', '', 'inline constexpr CommunityProfile CommunityProfiles[] = {', *profiles, '};', '}', ''])
    return '\n'.join(text)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--inventory', type=Path, required=True)
    parser.add_argument('--patches', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(generate(args.inventory, args.patches), encoding='utf-8', newline='\n')
